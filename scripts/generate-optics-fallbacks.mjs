#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadOptics } from '../test/helpers/optics-runtime.mjs'
import { decodePngDataUrl, encodePngRgba, hashPixels } from './png-codec.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'src', 'client', 'generated-optics-fallbacks.js')

const FALLBACKS = {
  sidebar: [244, 640],
  title: [720, 52],
  pane: [720, 560],
}

export async function renderFallbacks() {
  const api = await loadOptics()
  const maps = {}
  for (const [name, [w, h]] of Object.entries(FALLBACKS)) {
    const pixels = api.createIslandLensPixels(w, h)
    const map = encodePngRgba(pixels.width, pixels.height, pixels.data)
    const decoded = decodePngDataUrl(map)
    const pixelHash = hashPixels(decoded.data)
    if (pixelHash !== hashPixels(pixels.data)) {
      throw new Error(`fallback ${name} PNG round-trip changed pixels`)
    }
    maps[name] = {
      key: `${w}x${h}`,
      map,
      pixelHash,
      width: pixels.width,
      height: pixels.height,
    }
  }
  const json = JSON.stringify(maps, null, 2).replace(/^/gm, '    ')
  return `    // Generated by scripts/generate-optics-fallbacks.mjs. Do not edit by hand.
    var ISLAND_FALLBACK_MAPS = ${json.trim()}
`
}

export async function writeFallbacks() {
  const next = await renderFallbacks()
  await writeFile(outFile, next)
  return outFile
}

const invoked = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (invoked) {
  const check = process.argv.includes('--check')
  const expected = await renderFallbacks()
  if (check) {
    const actual = await readFile(outFile, 'utf8')
    if (actual !== expected) {
      console.error('src/client/generated-optics-fallbacks.js is stale. Run npm run generate:optics')
      process.exit(1)
    }
  } else {
    await writeFile(outFile, expected)
  }
}
